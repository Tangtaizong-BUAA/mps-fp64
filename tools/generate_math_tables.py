"""Regenerate the binary fixed-point Taylor tables with MPFR round-to-nearest-even."""

from math import factorial
from pathlib import Path

import gmpy2 as mp
from mpfr_enclosure import DirectedMath, Interval


def q(value, scale):
    scaled = value * (1 << scale)
    if isinstance(scaled, Interval):
        nearest = int(mp.rint(scaled.lo))
        if nearest != int(mp.rint(scaled.hi)):
            raise ArithmeticError(f"uncertain table rounding at Q{scale}")
        return nearest
    return int(mp.rint(scaled))


def split(value):
    head = q(value, 62)
    return head, q(value, 69) - (head << 7)


def node(a, scale=0, *, prescaled=False):
    vals = a if prescaled else [v / (1 << scale) for v in a]
    coeffs = ", ".join(f"{q(v,62)}l" for v in vals)
    assert all(abs(q(v, 62)) < 1 << 63 for v in vals)
    return f"    {{{{{coeffs}}}, {split(vals[0])[1]}, {scale}}},"


def tables(precision, arithmetic=mp):
    with mp.context(mp.get_context(), precision=precision, round=mp.RoundToNearest):
        grids = {
            n: []
            for n in (
                "trig",
                "tanh",
                "atan",
                "erf",
                "asinh",
                "exp",
                "log",
                "log2",
                "log10",
            )
        }
        log_constants = []
        for k in range(8 * 64 + 1):
            x = arithmetic.mpfr(k) / 64
            s, c = arithmetic.sin_cos(x)

            def trig_coeffs(v):
                return ", ".join(f"{q(v/factorial(n),62)}l" for n in range(1, 8))

            grids["trig"].append(
                f"    {{{{{trig_coeffs(s)}}}, {{{trig_coeffs(c)}}}, {split(s)[1]}, {split(c)[1]}}},"
            )
            a = [arithmetic.tanh(x)]
            for n in range(9):
                a.append(
                    ((n == 0) - sum(a[i] * a[n - i] for i in range(n + 1))) / (n + 1)
                )
            grids["tanh"].append(node(a))
            d = 1 + x * x
            a = [arithmetic.atan(x), 1 / d]
            h = [a[1]]
            for n in range(1, 9):
                h.append(-(2 * x * h[-1] + (h[-2] if n >= 2 else 0)) / d)
                a.append(h[-1] / (n + 1))
            grids["atan"].append(node(a))
            a = [
                arithmetic.erf(x),
                2 * arithmetic.exp(-x * x) / arithmetic.sqrt(arithmetic.const_pi()),
            ]
            for n in range(1, 9):
                a.append((-2 * x * n * a[n] - 2 * (n - 1) * a[n - 1]) / (n * (n + 1)))
            grids["erf"].append(node(a))
            a = [arithmetic.asinh(x), 1 / arithmetic.sqrt(d)]
            for n in range(1, 9):
                a.append(
                    -(x * n * (2 * n - 1) * a[n] + (n - 1) ** 2 * a[n - 1])
                    / (d * n * (n + 1))
                )
            grids["asinh"].append(node(a, 1))
        for k in range(-8 * 64, 8 * 64 + 1):
            x = arithmetic.mpfr(k) / 64
            f = arithmetic.exp(x)
            scale = max(0, int(arithmetic.get_exp(f)))
            a = [f / (1 << scale) / factorial(i) for i in range(10)]
            em1 = arithmetic.expm1(x) / (1 << scale)
            head, tail = split(em1)
            coefficients = node(a, scale, prescaled=True).strip().rstrip(",")
            grids["exp"].append(f"    {{{coefficients}, {head}l, {tail}}},")
        for name, base in [
            ("log", arithmetic.mpfr(1)),
            ("log2", arithmetic.log(2)),
            ("log10", arithmetic.log(10)),
        ]:
            c = arithmetic.log(2) / base
            ch = q(c, 62)
            log_constants.append(f"    {{{ch}l, {q(c,80)-(ch << 18)}}},")
            for k in range(64, 129):
                x = arithmetic.mpfr(k) / 64
                a = [getattr(arithmetic, name)(x)]
                for n in range(1, 10):
                    a.append((-1) ** (n - 1) / (n * x**n * base))
                grids[name].append(node(a))
    lines = [
        "// Generated by tools/generate_math_tables.py. The scales are described in fast_math.metal.",
        "struct TrigNode { long s[7], c[7]; short s_low, c_low; };",
        "struct TaylorNode { long a[10]; short low, scale; };",
        "struct ExpNode { TaylorNode poly; long minus_one; short minus_one_low; };",
        "struct LogConstant { long head; int tail; };",
    ]
    for name, rows in grids.items():
        typ = {"trig": "TrigNode", "exp": "ExpNode"}.get(name, "TaylorNode")
        lines += [f"constant {typ} {name}_grid[] = {{", *rows, "};"]
    return "\n".join(
        [*lines, "constant LogConstant log_constants[] = {", *log_constants, "};", ""]
    )


if __name__ == "__main__":
    output = tables(192)
    assert output == tables(320, DirectedMath())
    (
        Path(__file__).resolve().parents[1] / "mps_fp64/fast_math_tables.metal"
    ).write_text(output)
